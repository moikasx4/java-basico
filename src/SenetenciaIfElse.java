public class SenetenciaIfElse {
    public static void main(String[] args) {
        float promedio = 8.0f;
        if (promedio >= 7.5) {
            System.out.println("Buen promedio");
        } else if (promedio >= 6.0) {
            System.out.println("Debes esforzarte mas");
        } else if (promedio >= 5.5) {
            System.out.println("Lo siento tu compromiso no fue suficiente");
        } else if (promedio >= 5.0) {
            System.out.println("Considera tus acciones, influyen en tu futuro");
        } else if (promedio >= 4.5) {
            System.out.println("No tomes todo a la ligera");
        } else {
            System.out.println("Esfuerzate un poco mas");
        }

    }
}
